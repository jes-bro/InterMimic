#!/usr/bin/env python3
"""Curriculum controller: train ONE body-conditioned policy, no teachers.

Terminology (grounded in the env's config keys):
  source S = `dataSub`       — whose mocap MOTION is replayed as the reference.
  body   B = `subjectBodies`  — whose body MORPHOLOGY the policy controls.
  pair  S->B                  — drive body B using motion S. Identity when S==B.
(The weights-file key is `b{B}_s{S}` only because that mirrors the env's weight
tensor layout, row=body/col=motion — it carries no semantic priority.)

Folds OMOMO subjects in one at a time, resuming the previous checkpoint each
step, so a single network gradually learns to drive every body from every
source's motions. Held-out subjects ({4,10,16}) never enter. How a newly added
subject's pairs are introduced is set by --schedule:

  coarse                  — the whole subject lands at once: every pair in the
                            new active set (both directions) goes live in one
                            stage. The original behavior.
  identity-source-target  — each new subject N is folded over THREE sub-stages,
                            keeping all already-live pairs active throughout:
                              a) identity:  add  N -> N
                              b) as source: add  N -> bExisting
                              c) as target: add  sExisting -> N
                            The anchor subject gets only the identity sub-stage.

Sub-staging is implemented as a WEIGHT MASK: subjectBodies/dataSub always hold
the full active set, and the weights file carries 0 for not-yet-live pairs (so
torch.multinomial never samples them) and a positive weight for live ones. No
env change is needed beyond the existing subjectPairWeightsFile support.

Two pieces of automation (no human in the loop):

1. Plateau-triggered advancement. The controller launches a normal
   `intermimic.run` training subprocess, parses its `epoch_num:N mean_rewards:[X]`
   stdout, and advances to the next sub-stage once reward stops improving by
   more than `--improve-frac` for `--patience` epochs (after `--min-epochs`).
   This absorbs the reward dip that follows each new sub-stage. The cheap cross
   phases (source, target) get min-epochs/patience/stage-max divided by
   `--cross-epoch-divisor` (default 3); identity and coarse 'full' stages keep
   the full budget — this trims the "floor tax" of the many small sub-stages.

2. Pair balancing (--balance). Balancing is per (source, body) PAIR, not per
   subject. With `inverse-exposure` each sub-stage writes weights proportional
   to 1/(exposure so far) over the LIVE pairs, so freshly added pairs (zero
   exposure) get the most sampling and lifetime exposure equalizes across pairs.
   With `uniform` no weights file is written at all, so pairs are sampled
   uniformly at random (only valid with --schedule coarse — sub-staging needs
   the mask). Note: a pair is only reachable if some env physically owns a
   shared object — the env prints a WARNING listing any unreachable pairs.
   `--exposure` controls how the exposure feeding those weights is tracked:
   `estimated` (epochs * normalized weight) or `measured` (the env counts the
   ACTUAL (source,body) samples per sub-stage and the controller reweights from
   true counts AND reports leaks — masked pairs the fallback still drew).

Run (normally inside one slurm job holding one GPU):
  # experimental: sub-staged fold-in with inverse-exposure balancing
  python scripts/curriculum_runner.py --run-name ist
  # baseline: whole subject at once, plain random pair sampling
  python scripts/curriculum_runner.py --run-name baseline --schedule coarse --balance uniform
Validate config generation without launching training:
  python scripts/curriculum_runner.py --run-name ist --dry-run
"""

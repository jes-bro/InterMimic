def yaml_sub_list(subjects):
    """['sub2', 'sub3'] formatting for a list of subject ints."""
    return "[" + ", ".join(f"'sub{n}'" for n in subjects) + "]"


def compute_pair_weights(bodies, sources, live, exposure, eps=1.0):
    """Per (source, body) pair weight: inverse-exposure for live, 0 otherwise.

    `bodies` and `sources` are usually the same active set, but differ when
    target-only synthetic bodies are folded in (they appear as bodies, never as
    sources). `live` is the set of (s, b) tuples currently allowed to be
    sampled. Live pairs get weight ∝ 1/(exposure + eps), normalized to mean 1
    over the live set (scale is irrelevant to multinomial sampling but keeps
    numbers readable). Not-yet-live pairs are written as an explicit 0.0 — the
    env defaults a MISSING key to 1.0, so we must emit the zero to mask them
    out. Keys are 'b{B}_s{S}' to match what the env reads (body-first layout).
    """
    w, live_vals = {}, {}
    for b in bodies:
        for s in sources:
            key = f"b{b}_s{s}"
            if (s, b) in live:
                live_vals[key] = 1.0 / (exposure.get(key, 0.0) + eps)
            else:
                w[key] = 0.0  # masked: never sampled this sub-stage
    mean = (sum(live_vals.values()) / len(live_vals)) if live_vals else 1.0
    for k, v in live_vals.items():
        w[k] = v / mean
    return w


def build_substages(order, schedule):
    """Expand the fold-in order into a flat list of sub-stage descriptors.

    Each descriptor carries the cumulative set of LIVE (source, body) pairs at
    that point — already-live pairs persist across sub-stages so the policy
    keeps rehearsing them (anti-forgetting). Fields:
      stage    1-based subject index (which subject is being folded in)
      suffix   unique tag for dirs/filenames, e.g. '03' (coarse) or '03b' (ist)
      phase    'full' | 'identity' | 'source' | 'target'
      new      the subject number being folded in at this sub-stage
      bodies   subjectBodies for the env (full active set)
      sources  dataSub for the env (full active set)
      live     set of (s, b) tuples allowed to be sampled (the weight mask)
    """
    subs, live = [], set()
    for st, n in enumerate(order):
        prev = order[:st]              # subjects already present before N
        active = sorted(order[:st + 1])
        if schedule == "coarse":
            # Whole subject at once: every pair (both directions) goes live.
            for s in active:
                for b in active:
                    live.add((s, b))
            subs.append(dict(stage=st + 1, suffix=f"{st + 1:02d}", phase="full",
                             new=n, bodies=active, sources=active, live=set(live)))
        else:  # identity-source-target
            live.add((n, n))           # a) identity: N -> N
            subs.append(dict(stage=st + 1, suffix=f"{st + 1:02d}a", phase="identity",
                             new=n, bodies=active, sources=active, live=set(live)))
            if prev:
                for b in prev:         # b) as source: N's motion -> existing bodies
                    live.add((n, b))
                subs.append(dict(stage=st + 1, suffix=f"{st + 1:02d}b", phase="source",
                                 new=n, bodies=active, sources=active, live=set(live)))
                for s in prev:         # c) as target: existing motions -> N's body
                    live.add((s, n))
                subs.append(dict(stage=st + 1, suffix=f"{st + 1:02d}c", phase="target",
                                 new=n, bodies=active, sources=active, live=set(live)))
    return subs


def inject_synthetic(real_subs, order, syn_ids, position, mode, batch_size):
    """Fold target-only synthetic bodies into the substage list.

    Synthetic bodies (subject ids >= synthetic-start-id, e.g. sub100..) are
    BODIES the policy controls but never SOURCES -- they're driven by the real
    sources, scored against the real reference (no GT of their own). So their
    live pairs are (real_source, syn_body) only.

    position: 'append'     -> all synthetic stages after the full real curriculum
              'interleave'  -> spread between the real stages (each syn body then
                               pairs only with the real sources live SO FAR, and
                               later real sources retro-pair with it).
    mode:     'staged'      -> one synthetic body per stage (batch_size forced 1)
              'batched'     -> batch_size synthetic bodies per stage
    Returns a new substage list with cumulative live/bodies/sources recomputed.
    """
    if not syn_ids:
        return real_subs
    bs = 1 if mode == "staged" else max(1, batch_size)
    batches = [syn_ids[i:i + bs] for i in range(0, len(syn_ids), bs)]

    # new real pairs introduced at each real substage (cumulative -> per-stage delta)
    real_new, prev = [], set()
    for ss in real_subs:
        real_new.append(ss["live"] - prev)
        prev = ss["live"]

    # which real substage index each batch is inserted AFTER
    after = {}
    n = len(real_subs)
    if position == "append":
        after[n - 1] = list(batches)
    else:  # interleave: evenly spaced across the real stages
        for k, b in enumerate(batches):
            pos = min(n - 1, int((k + 1) * n / (len(batches) + 1)))
            after.setdefault(pos, []).append(b)

    merged, cum, syn_live, real_src = [], set(), [], set()
    syn_n = 0
    for ridx, ss in enumerate(real_subs):
        cum |= real_new[ridx]
        # a newly-live real source retro-pairs with every synthetic body so far
        for s in {s for (s, _) in real_new[ridx]} - real_src:
            real_src.add(s)
            cum |= {(s, syn_b) for syn_b in syn_live}
        merged.append({**ss, "bodies": sorted({b for (_, b) in cum}),
                       "sources": sorted({s for (s, _) in cum}), "live": set(cum)})
        for batch in after.get(ridx, []):
            for syn_b in batch:
                cum |= {(s, syn_b) for s in real_src}   # driven by real sources live so far
                syn_live.append(syn_b)
            syn_n += 1
            merged.append(dict(stage=ss["stage"], suffix=f"y{syn_n:02d}",
                               phase="synthetic", new=batch[0],
                               bodies=sorted({b for (_, b) in cum}),
                               sources=sorted({s for (s, _) in cum}), live=set(cum)))
    return merged


def update_exposure(exposure, active, weights, epochs):
    """Accumulate per-pair exposure ≈ epochs * (this pair's sampling fraction).

    Sampling fraction ≈ normalized weight, so high-weight pairs gain exposure
    fastest — which then lowers their weight next stage. Closes the balancing
    loop toward equal lifetime exposure.
    """
    total = sum(weights.values())
    for key, w in weights.items():
        exposure[key] = exposure.get(key, 0.0) + epochs * (w / total)


def latest_checkpoint(exp_name):
    """Newest complete snapshot checkpoints/<exp>/nn/mimic_<frames>.pth, else mimic.pth."""
    nn = REPO / "checkpoints" / exp_name / "nn"
    if not nn.is_dir():
        return None
    snaps = []
    for p in nn.glob("mimic_*.pth"):
        m = re.search(r"mimic_(\d+)\.pth$", p.name)
        if m:
            snaps.append((int(m.group(1)), p))
    if snaps:
        return max(snaps)[1]
    last = nn / "mimic.pth"
    return last if last.exists() else None


def terminate(proc, grace=20):
    """Stop the training subprocess: SIGTERM, wait, then SIGKILL."""
    if proc.poll() is not None:
        return
    proc.terminate()
    try:
        proc.wait(timeout=grace)
    except subprocess.TimeoutExpired:
        proc.kill()
        proc.wait()


def run_stage(env_cfg, train_cfg, exp_name, log_path, args,
              min_epochs, patience, stage_max_epochs):
    """Launch one sub-stage; return (epochs_run, exited_on_own).

    Streams the training stdout to both log_path and our stdout (so it lands in
    the slurm .out), watches reward, and stops the subprocess on plateau / cap.
    The plateau thresholds (min_epochs, patience, stage_max_epochs) are passed
    in per-sub-stage so cheap cross phases can run on a smaller budget than the
    identity phase; improve_frac still comes from args (it's global).
    """
    cmd = [sys.executable, "-u", "-m", "intermimic.run",
           "--task", "InterMimic",
           "--cfg_env", env_cfg, "--cfg_train", train_cfg,
           "--headless", "--output", "checkpoints"]
    env = os.environ.copy()
    # Mirror what the train shells set so `intermimic` is importable.
    src = str(REPO / "isaacgym" / "src")
    env["PYTHONPATH"] = os.pathsep.join(
        [src, str(REPO), env.get("PYTHONPATH", "")]).strip(os.pathsep)

    print(f"[curriculum] launching: {' '.join(cmd)}", flush=True)
    proc = subprocess.Popen(cmd, cwd=str(REPO), stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, text=True, bufsize=1, env=env)

    # rl_games restores epoch_num on warm-start, so the printed epoch counter is
    # CUMULATIVE across stages (stage 2 may start near epoch 3000). All our
    # thresholds are therefore measured relative to this stage's first epoch.
    best, best_epoch = float("-inf"), None
    stage_start_epoch, last_epoch = None, None
    advancing = False
    with open(log_path, "w") as logf:
        for line in proc.stdout:
            logf.write(line)
            sys.stdout.write(line)
            sys.stdout.flush()
            m = REWARD_RX.search(line)
            if not m:
                continue
            ep = int(m.group(1))
            try:
                rew = float(m.group(2))
            except ValueError:
                continue
            if stage_start_epoch is None:
                stage_start_epoch = ep
            last_epoch = ep
            in_stage = ep - stage_start_epoch
            # An "improvement" must beat the best by > improve_frac.
            improved = (rew > best * (1.0 + args.improve_frac)) if best > 0 else (rew > best)
            if improved:
                best, best_epoch = rew, ep
            if in_stage >= min_epochs and (ep - best_epoch) >= patience:
                print(f"[curriculum] PLATEAU {exp_name}: epoch {ep} (+{in_stage} in stage), "
                      f"best {best:.3f}@{best_epoch} (no >{args.improve_frac:.0%} gain in "
                      f"{patience} epochs) -> advance", flush=True)
                advancing = True
                break
            if in_stage >= stage_max_epochs:
                print(f"[curriculum] CAP {exp_name}: +{in_stage} epochs in stage "
                      f"(stage_max_epochs={stage_max_epochs}) -> advance", flush=True)
                advancing = True
                break
    epochs_in_stage = (last_epoch - stage_start_epoch) if stage_start_epoch is not None else 0
    exited_on_own = proc.poll() is not None and not advancing
    terminate(proc)
    return epochs_in_stage, exited_on_own


